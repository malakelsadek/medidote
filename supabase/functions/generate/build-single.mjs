// Bundles the function's files into ONE file you can paste into the Supabase dashboard editor (Edge Functions, generate, Code).
// Run from the project folder:   node supabase/functions/generate/build-single.mjs
// It writes supabase/paste-into-dashboard/generate.ts. The normal route (supabase functions deploy generate) does not need this.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const here = (f) => new URL(f, import.meta.url);
const read = (f) => readFileSync(here(f), "utf8").replace(/\r\n/g, "\n");
const noExport = (s) => s.replace(/^export /gm, "");

const index = read("./index.ts")
  .replace(/^import \{[^}]*\} from "\.\/[^"]+";\n/gm, "")             // local imports are inlined below
  .replace(/^import guide from "\.\/guide\.json"[^\n]*\n/m, "");
const out = [
  "// Single-file build of the generate function. Generated by build-single.mjs: edit the separate files, then run it again.",
  index.slice(0, index.indexOf("\n\nconst MODEL")),                      // header comment and the npm imports
  "// ---- guide.json ----",
  `const guide: Guide = ${JSON.stringify(JSON.parse(read("./guide.json")), null, 2)};`,
  "// ---- guide.ts ----",
  noExport(read("./guide.ts")),
  "// ---- balance.ts ----",
  noExport(read("./balance.ts")),
  "// ---- pdfpages.ts ----",
  noExport(read("./pdfpages.ts")),
  "// ---- index.ts ----",
  index.slice(index.indexOf("const MODEL")),
].join("\n\n");

mkdirSync(here("../../paste-into-dashboard/"), { recursive: true });
writeFileSync(here("../../paste-into-dashboard/generate.ts"), out);
console.log("wrote supabase/paste-into-dashboard/generate.ts (" + out.length + " characters)");
